import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_URL || 'http://localhost:5000/api';

export const apiClient = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
  timeout: 30000,
});

apiClient.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('ciphersense_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

apiClient.interceptors.response.use(
  (response) => response,
  (error) => {
    // Authentication state is restored from local storage by AuthContext.
    // Do not globally erase or redirect on an API-level 401, because a
    // transient service/database failure or an endpoint-specific auth check
    // must not unexpectedly log an otherwise valid session out.
    return Promise.reject(error);
  }
);
